#Leia dois números inteiros. Exiba, cada um em sua linha e devidamente identificado:
#a soma, a
#divisão comum, a divisão inteira, o resto da divisão e o primeiro número elevado ao 
#segundo.


a = int(input("Digite o primeir numero: "))
b = int(input("Digite o segundo numero: "))
print("\n")

print("A divizão entre os numeros: ")
print(a / b)
print("A divizão inteira entre os números: ")
print(a // b)
print("O resto da divizão enre os dois numeros: ")
print(a % b)
print("Primeiro número elevado ao segundo: ")
print(a ** b)
print("\n")